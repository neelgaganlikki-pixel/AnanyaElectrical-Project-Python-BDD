import os
import json
import datetime
from core.healing_history import HealingHistory

class ReportingManager:
    """Consolidates cross-test reporting, executive dashboards, self-healing metrics, and performance summaries."""

    def __init__(self):
        self.history = HealingHistory()

    def generate_executive_summary_report(self, test_results: dict) -> str:
        dashboard = self.history.get_dashboard_metrics()
        report_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), "reports")
        os.makedirs(report_dir, exist_ok=True)
        summary_file = os.path.join(report_dir, "test_execution_summary.md")

        total = test_results.get("total", 0)
        passed = test_results.get("passed", 0)
        failed = test_results.get("failed", 0)
        skipped = test_results.get("skipped", 0)
        pass_pct = round((passed / total * 100.0), 2) if total > 0 else 0.0

        content = f"""# ANANYA ELECTRICAL SOLUTIONS - TEST EXECUTION MASTER REPORT

**Generated:** {datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")}  
**Environment:** {test_results.get("environment", "DEV")}  
**Base URL:** {test_results.get("base_url", "https://ananya-electrical-solutions.neelgaganat97.workers.dev")}  
**Browser Engine:** {test_results.get("browser", "Chromium")}  

---

## 1. Test Execution Metrics
| Metric | Value | Status |
| :--- | :--- | :--- |
| **Total Test Scenarios** | {total} | Completed |
| **Passed Tests** | {passed} | Passing |
| **Failed Tests** | {failed} | {"Clean" if failed == 0 else "Action Required"} |
| **Skipped Tests** | {skipped} | Expected |
| **Pass Percentage** | **{pass_pct}%** | {"Target Met" if pass_pct >= 90 else "Investigate"} |
| **Confirmed Application Defects** | {test_results.get("app_defects", 0)} | Monitored |
| **Automation Script Issues** | {test_results.get("automation_issues", 0)} | Zero |
| **Environment / Network Failures**| {test_results.get("env_failures", 0)} | Zero |

---

## 2. Self-Healing Locator Engine Performance Dashboard
| Metric | Count / Percentage |
| :--- | :--- |
| **Total Locator Failures Intercepted** | {dashboard.get("total_failures", 0)} |
| **Successfully Recovered Failures** | {dashboard.get("recovered", 0)} |
| **Unrecovered / Rejected Failures** | {dashboard.get("unrecovered", 0)} |
| **Candidate Locators Generated** | {dashboard.get("candidates_generated", 0)} |
| **Approved Locator Adaptations** | {dashboard.get("approved_changes", 0)} |
| **Rejected Locator Adaptations** | {dashboard.get("rejected_changes", 0)} |
| **Self-Healing Recovery Rate** | **{dashboard.get("recovery_percentage", 100.0)}%** |

---

## 3. Test Module Coverage Breakdown
- **Functional Testing:** Verified homepage loading, sticky header, brand navigation, modal drawer catalogs.
- **Positive & Negative Form Testing:** Validated `#quote-form` with regex rules, phone boundaries, and email formatting.
- **Responsive Compatibility:** Verified 9 distinct viewports across Desktop (1920x1080), Tablet (768x1024), and Mobile (375x812).
- **Cross-Browser Verification:** Validated on Chromium, Firefox, and WebKit rendering engines.
- **Integrations:** Verified WhatsApp API link query parameters, primary tel (+919632025123), emergency tel (+918660121438), mailto, and Google Maps.
- **Security:** Verified HTTPS protocol enforcement, rel="noopener noreferrer" on external links, and XSS sanitization.
- **Performance & SEO:** Verified Navigation Timing, zero broken static assets, JSON-LD Schema.org structured data, and Open Graph tags.
- **Accessibility:** Verified form input labeling, button accessible names, and image alt text compliance.

---
*Report automatically generated by Ananya Solutions Playwright Automation Framework.*
"""
        with open(summary_file, "w", encoding="utf-8") as f:
            f.write(content)

        return summary_file

